/* 查证之后柜台底下那行小字 */
export function idLine(s) {
    if (!s.checked) { return ''; }
    switch (s.kind) {
        case KIND.minor: return '身份证：2009 年生。还差两年。';
        case KIND.noid: return '身份证：没有。他说忘在车里，可外面没有车。';
        case KIND.shady: return '身份证：照片对不上。他的手一直没离开柜台。';
        case KIND.shadow: return '身份证：你翻了两遍，没有找到出生日期那一栏。';
        case KIND.drunk: return '驾驶证：过期两年。他还在等你开酒。';
        case KIND.regular: return '熟客。没有必要看，他还是把证件推了过来。';
        default: return '身份证：一切正常。他开始不耐烦了。';
    }
}

