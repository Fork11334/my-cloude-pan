/* 来客开口说的第一句。注意：未成年、缺证、可疑看起来都只是普通顾客，
   差别只在画面上，以及查证之后的那一行。 */
export function customerLine(s) {
    if (s.kind === KIND.shadow) { return '它没有说话。柜台上的灯闪了一下。'; }
    if (s.kind === KIND.shady) { return SHADY_LINE[(s.demand + s.total) % SHADY_LINE.length]; }
    if (s.kind === KIND.drunk) { return '两罐……嗝……两罐啤酒。'; }
    return DEMAND[s.demand] ?? DEMAND[0];
}

